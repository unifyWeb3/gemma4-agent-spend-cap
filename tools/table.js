/**
 * Build the paper's results table from the raw records.
 *
 * The table in `paper.md` must not be typed by hand. This script reads the
 * raw JSON records of both arms, groups them the same way `summarise` in
 * `harness/run.js` does, and writes `results/table.md`.
 *
 * It also prints the delivery failures, because a cell where the injection
 * never reached the model is not evidence about the defence.
 *
 * Usage:
 *   node tools/table.js
 *   node tools/table.js --control results/control-v2 --model results/gemma-ai-studio-v2
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { summarise } from '../harness/run.js';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Read every episode record in one results directory. */
export function readRecords(dir) {
  const full = join(REPO, dir);
  const records = [];
  for (const name of readdirSync(full)) {
    if (!name.endsWith('.json') || name === 'summary.json') continue;
    records.push(JSON.parse(readFileSync(join(full, name), 'utf8')));
  }
  return records;
}

/** One arm's summary plus the delivery failures. */
export function arm(dir) {
  const records = readRecords(dir);
  const errors = records.filter((r) => r.error);
  const failures = records.filter((r) => !r.error && !r.injectionExposed);
  return {
    dir,
    records,
    summary: summarise(records),
    errors,
    failures,
  };
}

/** Render the combined table. */
export function table(arms) {
  const head =
    '| arm | attack | defence | runs | exposed | attack success | success given exposed | mean loss cents | task completion | patch verified | lookup done | legit blocked | step capped | refused calls | mean steps |';
  const sep = `| ${'--- | '.repeat(14)}---|`;
  const rows = [];
  for (const [label, a] of arms) {
    for (const s of a.summary) {
      rows.push(
        `| ${label} | ${s.attack} | ${s.defense} | ${s.runs} | ${(s.exposureRate * 100).toFixed(0)}% | ${(s.attackSuccessRate * 100).toFixed(0)}% | ${s.successGivenExposure === null ? 'n/a' : `${(s.successGivenExposure * 100).toFixed(0)}%`} | ${s.meanLossCents.toFixed(1)} | ${(s.taskCompletion * 100).toFixed(0)}% | ${s.verifiedPatchRate === null ? 'n/a' : `${(s.verifiedPatchRate * 100).toFixed(0)}%`} | ${(s.lookupRate * 100).toFixed(0)}% | ${(s.falsePositiveRate * 100).toFixed(0)}% | ${s.cappedRuns} | ${s.refusedPayments.toFixed(1)} | ${s.meanSteps.toFixed(1)} |`,
      );
    }
  }
  return [head, sep, ...rows].join('\n');
}

/** A short audit line per arm. */
export function audit(label, a) {
  const total = a.records.length;
  const exposed = a.records.filter((r) => !r.error && r.injectionExposed).length;
  const paid = a.records.filter((r) => !r.error && r.attackSuccess).length;
  return [
    `${label}: ${total} records, ${a.errors.length} errors, ${exposed} exposed, ${paid} attacks paid`,
    a.errors.length ? `  errors: ${a.errors.map((r) => r.runId).join(', ')}` : null,
    a.failures.length
      ? `  delivery failures: ${a.failures.map((r) => `${r.runId} (${r.exposureRoute ?? 'no route'})`).join(', ')}`
      : null,
  ]
    .filter(Boolean)
    .join('\n');
}

function parseArgs(argv) {
  const args = { control: 'results/control-v2', model: 'results/gemma-ai-studio-v2' };
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--control') args.control = argv[++i];
    if (argv[i] === '--model') args.model = argv[++i];
  }
  return args;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const control = arm(args.control);
  const model = arm(args.model);
  const arms = [
    ['control', control],
    ['gemma', model],
  ];
  const md = `# Results table\n\nGenerated by \`node tools/table.js\` from the raw records. Do not edit by hand.\n\n${table(arms)}\n`;
  writeFileSync(join(REPO, 'results/table.md'), md);
  for (const [label, a] of arms) console.log(audit(label, a));
  console.log('\n' + table(arms));
  console.log('\nwritten to results/table.md');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
